#!/usr/bin/env python3
"""Adapt the owner's binary control to dpkg-gencontrol's source format."""
import argparse
from email.parser import Parser
from pathlib import Path
import re

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("original", type=Path)
parser.add_argument("control", type=Path)
parser.add_argument("changelog", type=Path)
args = parser.parse_args()
text = args.original.read_text()
fields = Parser().parsestr(text)
if fields["Package"] != "symcrypt-openssl" or fields["Version"] != "1.11.0":
    raise SystemExit("The original SymCrypt package identity changed; update the package contract")
if fields["Architecture"] != "all":
    raise SystemExit("Review the original package architecture change")
# The original Make control calls its ELF payload Architecture: all. A native
# Bazel package must identify its actual architecture. Preserve the remaining
# owner fields and append dependencies resolved from those same ELF files.
binary = re.sub(r"^(?:Version|Maintainer):[^\n]*\n", "", text, flags=re.MULTILINE)
binary = binary.replace("Architecture: all\n", "Architecture: any\n")
binary = binary.replace("Depends: " + fields["Depends"], "Depends: " + fields["Depends"] + ", ${shlibs:Depends}, ${misc:Depends}")
args.control.write_text("Source: symcrypt-openssl\nMaintainer: " + fields["Maintainer"] + "\n\n" + binary)
args.changelog.write_text(
    "symcrypt-openssl (" + fields["Version"] + ") unstable; urgency=medium\n\n"
    "  * AUTO-GENERATED by symcrypt/debian/source_control.py. DO NOT EDIT.\n"
    "  * Adapt the existing binary package metadata for dpkg-gencontrol.\n\n"
    " -- " + fields["Maintainer"] + "  Thu, 01 Jan 1970 00:00:00 +0000\n")
